print("[웨이퍼 생산 제어 판정 결과]")
print("웨이퍼 개수:", wafer_count)
print("전체 칩 수:", total_chips)
print("불량 칩 수:", defective_chips)
print("수율:", round(yield_rate, 2), "%")
print("온도:", temperature, "| 상태:", temperature_status)
print("압력:", pressure, "| 상태:", pressure_status)
print("수율 상태:", yield_status)
print("최종 판정:", decision)