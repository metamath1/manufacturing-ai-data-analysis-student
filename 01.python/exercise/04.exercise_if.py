# ============================================================
# 조건문을 이용한 웨이퍼 생산제어 프로그램 작성
# ============================================================
# 이 예제는 실제 반도체 장비를 제어하는 프로그램이 아닙니다.
# if, else 조건문을 사용하여 생산 진행 여부를 판단하는
# 교육용 예제입니다.
#
# 연산자 실습에서 계산한 수율과 공정값을 바탕으로
# 이번에는 사람이 읽을 수 있는 상태 메시지를 만듭니다.
#
# 학습 목표:
# - if, else 조건문을 사용한다.
# - 비교 연산자와 논리 연산자를 조건식 안에서 사용한다.
# - 여러 판정 결과를 종합하여 최종 판단을 만든다.
#
# 주의:
# 아래 기준값은 실제 공정 기준이 아닙니다.
# 파이썬 조건문 학습을 위한 교육용 가상 기준입니다.
# ============================================================

# ------------------------------------------------------------
# 교육용 가상 생산 데이터
# 실제 생산 데이터가 아닙니다.
# ------------------------------------------------------------
wafer_count = 3
chips_per_wafer = 650
defective_chips = 42

temperature = 73.5
pressure = 1.8

# ------------------------------------------------------------
# 교육용 가상 기준값
# 실제 공정 기준이 아닙니다.
# ------------------------------------------------------------
min_temperature = 70.0
max_temperature = 75.0

min_pressure = 1.5
max_pressure = 2.0

min_yield_rate = 95.0


# ------------------------------------------------------------
# 제공 코드: 수율 계산
# 조건문 실습의 초점은 if문이므로
# 수율 계산 코드는 미리 제공합니다.
# ------------------------------------------------------------
total_chips = wafer_count * chips_per_wafer
good_chips = total_chips - defective_chips
yield_rate = good_chips / total_chips * 100


temperature_status = ""
pressure_status = ""
yield_status = ""
decision = ""


# ============================================================
# 수강생 작성 영역
#
# 목표:
# 조건문을 사용해 각 상태를 판정하세요.
#
# 1. temperature_status
#    온도가 min_temperature 이상 max_temperature 이하이면 "정상"
#    그렇지 않으면 "기준 이탈"
#
# 2. pressure_status
#    압력이 min_pressure 이상 max_pressure 이하이면 "정상"
#    그렇지 않으면 "기준 이탈"
#
# 3. yield_status
#    수율이 min_yield_rate 이상이면 "정상"
#    그렇지 않으면 "기준 미달"
#
# 4. decision
#    온도, 압력, 수율 상태가 모두 "정상"이면 "생산 계속 진행"
#    하나라도 정상이 아니면 "생산 중지 후 점검 필요"
#
# 주의:
# 이 판단은 실제 장비 제어가 아니라
# 조건문 연습을 위한 교육용 판정입니다.
# ============================================================

