import random
import time


# ------------------------------------------------------------
# 교육용 공정명 목록
# 실제 공정 전체를 표현한 것이 아니라,
# 예제 데이터에 업무 맥락을 주기 위한 간단한 이름입니다.
# ------------------------------------------------------------
process_names = ["증착", "식각", "세정", "노광", "검사"]


def create_batch_data(batch_no):
    # --------------------------------------------------------
    # 교육용 가상 공정 데이터 생성 함수
    # 실제 생산 DB에서 데이터를 읽는 것이 아니라,
    # random으로 5건의 가상 데이터를 생성합니다.
    #
    # 함수 문법을 아직 자세히 배우지 않았더라도,
    # 이 함수는 "데이터를 준비해주는 제공 코드"로 보면 됩니다.
    # --------------------------------------------------------
    batch_data = []

    for i in range(5):
        wafer_id = "B" + str(batch_no) + "-WAFER-" + str(i + 1).zfill(3)
        process = random.choice(process_names)
        temperature = round(random.uniform(68.0, 77.0), 1)
        defect_count = random.randint(0, 10)

        data = {
            "wafer_id": wafer_id,
            "process": process,
            "temperature": temperature,
            "defect_count": defect_count
        }

        batch_data.append(data)

    return batch_data


